"""Write constraints.txt: the exact version of every package requirements.txt pulls in (transitively),
as installed in THIS environment — run it with production's interpreter on the i9:

    venv/bin/python scripts/gen_constraints.py

Both machines then install with `pip install -r requirements.txt -c constraints.txt`, so the droplet
runs the libraries production runs (DEPLOY.md, step 5). Regenerate and commit whenever production's
libraries change; nothing else is listed (test and dev tools are not part of the server).

    python scripts/gen_constraints.py --check

recomputes the same list in the running environment and exits 1 unless it equals constraints.txt
exactly (every package of the closure pinned, at the version installed, and nothing else) — run by
scripts/deploy_xps2.sh on the i9 before deploying and on the droplet after installing."""
import importlib.metadata as md
import re
import sys
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parent.parent


def _canon(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def closure():
    """{canonical name: "Name==version"} for requirements.txt's closure in this environment."""
    roots = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if line:
            roots.append(Requirement(line).name)
    pinned, stack = {}, list(roots)
    while stack:
        name = _canon(stack.pop())
        if name in pinned:
            continue
        dist = md.distribution(name)                       # raises if production lacks a requirement
        pinned[name] = f"{dist.metadata['Name']}=={dist.version}"
        for req in dist.requires or []:
            r = Requirement(req)
            if r.marker and not r.marker.evaluate({"extra": ""}):
                continue
            stack.append(r.name)
    return pinned


HEADER = ("# Generated by scripts/gen_constraints.py from production's environment (the i9) — do not edit.\n"
          "# Install: pip install -r requirements.txt -c constraints.txt\n")


def main():
    path = ROOT / "constraints.txt"
    try:
        pinned = closure()
    except md.PackageNotFoundError as e:
        sys.exit(f"a requirement is not installed here: {e}")
    body = "\n".join(pinned[k] for k in sorted(pinned))
    if sys.argv[1:] == ["--check"]:
        listed = {_canon(l.split("==")[0]): l for l in path.read_text().splitlines()
                  if l.strip() and not l.startswith("#")}
        diff = [f"{listed.get(k, '(not listed)')} -> installed {pinned.get(k, '(not in the closure)')}"
                for k in sorted(set(listed) | set(pinned)) if listed.get(k) != pinned.get(k)]
        if diff:
            sys.exit("constraints.txt differs from this environment: " + "; ".join(diff))
        print(f"constraints.txt equals this environment ({len(pinned)} packages)")
        return
    path.write_text(HEADER + body + "\n")
    print(body)


if __name__ == "__main__":
    main()
